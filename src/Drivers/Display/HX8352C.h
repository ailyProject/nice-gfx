inline void rotate_HX8352C(PanelSequence &s, uint8_t m) {
s.rotation = m % 4;
  switch (s.rotation) {
    case 0: s.writecommand(0x36); s.writedata(0x07); s.writecommand(0x16); s.writedata(0x40); s._width = s._init_width; s._height = s._init_height; break;
    case 1: s.writecommand(0x36); s.writedata(0x03); s.writecommand(0x16); s.writedata(0x60); s._width = s._init_height; s._height = s._init_width; break;
    case 2: s.writecommand(0x36); s.writedata(0x03); s.writecommand(0x16); s.writedata(0x00); s._width = s._init_width; s._height = s._init_height; break;
    case 3: s.writecommand(0x36); s.writedata(0x07); s.writecommand(0x16); s.writedata(0x20); s._width = s._init_height; s._height = s._init_width; break;
  }
}
