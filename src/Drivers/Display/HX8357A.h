inline void rotate_HX8357A(PanelSequence &s, uint8_t m) {
s.rotation = m % 4;
  s.writecommand(0x16);
  switch (s.rotation) {
    case 0: s.writedata(0x80 | s.colorOrder); s._width = s._init_width; s._height = s._init_height; break;
    case 1: s.writedata(0x60 | s.colorOrder); s._width = s._init_height; s._height = s._init_width; break;
    case 2: s.writedata(0x40 | s.colorOrder); s._width = s._init_width; s._height = s._init_height; break;
    case 3: s.writedata(0xA0 | s.colorOrder); s._width = s._init_height; s._height = s._init_width; break;
  }
}
